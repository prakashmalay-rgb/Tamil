def main():
    out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "data")
    os.makedirs(out_dir, exist_ok=True)
    out_file = os.path.join(out_dir, "tamil_gold_multiturn.jsonl")

    # Clean and validate each conversation via grammar_validator
    validated_conversations = []
    for conv in GOLD_CONVERSATIONS:
        cleaned_msgs = []
        for msg in conv["messages"]:
            content = msg["content"]
            if msg["role"] == "assistant":
                content = validator.correct_sandhi(content)
                content = validator.correct_orthography(content)
                content = validator.ensure_complete_sentence(content)
            cleaned_msgs.append({"role": msg["role"], "content": content})
        validated_conversations.append({"messages": cleaned_msgs})

    # Write gold file
    with open(out_file, "w", encoding="utf-8") as f:
        for conv in validated_conversations:
            f.write(json.dumps(conv, ensure_ascii=False) + "\n")

    print(f"Successfully built gold multi-turn corpus at: {out_file}")
    print(f"Total conversation sessions: {len(validated_conversations)}")

